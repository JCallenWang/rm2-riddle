// Glyph 回傳某字符的字形;小寫回退為大寫。第二回傳值表示是否已定義。
func glyphFor(r rune) (glyph, bool) {
	if g, ok := table[r]; ok {
		return g, true
	}
	if r >= 'a' && r <= 'z' {
		if g, ok := table[r-'a'+'A']; ok {
			return g, true
		}
	}
	return table[' '], false
}
